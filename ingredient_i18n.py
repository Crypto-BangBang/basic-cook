def translate_ing_name(name: str, lang: str) -> str:
    if lang == "ko":
        return name
    if name in ING_NAMES:
        return ING_NAMES[name].get(lang, name)
    # partial match: try base names
    for base, trans in _BASE_NAMES.items():
        if base in name:
            translated_base = trans.get(lang, base)
            remainder = name.replace(base, "", 1).strip()
            return f"{translated_base} {remainder}".strip() if remainder else translated_base
    return name


